-- PharmaGestion schema for Supabase / PostgreSQL.
-- Run this whole file in Supabase Dashboard > SQL Editor on a new project.

CREATE TABLE IF NOT EXISTS utilisateurs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(100) NOT NULL,
    prenom VARCHAR(100) NOT NULL,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'PHARMACIEN'
        CHECK (role IN ('ADMIN', 'PHARMACIEN')),
    actif BOOLEAN NOT NULL DEFAULT TRUE,
    date_creation TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS categories (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(100) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE IF NOT EXISTS medicaments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(200) NOT NULL,
    dosage VARCHAR(100),
    forme VARCHAR(100),
    description TEXT,
    categorie_id INTEGER NOT NULL REFERENCES categories(id)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    prix_achat DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    prix_vente DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    quantite_stock INTEGER NOT NULL DEFAULT 0 CHECK (quantite_stock >= 0),
    seuil_alerte INTEGER NOT NULL DEFAULT 10 CHECK (seuil_alerte >= 0),
    date_expiration DATE,
    code_barre VARCHAR(50) UNIQUE
);

CREATE TABLE IF NOT EXISTS lots_medicaments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medicament_id INTEGER NOT NULL REFERENCES medicaments(id)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    numero_lot VARCHAR(80) NOT NULL,
    date_expiration DATE NOT NULL,
    quantite_initiale INTEGER NOT NULL CHECK (quantite_initiale >= 0),
    quantite_disponible INTEGER NOT NULL CHECK (quantite_disponible >= 0
        AND quantite_disponible <= quantite_initiale),
    prix_achat DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    date_reception TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_lot_medicament UNIQUE (medicament_id, numero_lot)
);
CREATE INDEX IF NOT EXISTS idx_lots_fefo
    ON lots_medicaments (medicament_id, date_expiration, quantite_disponible);

CREATE TABLE IF NOT EXISTS fournisseurs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(200) NOT NULL,
    adresse TEXT,
    telephone VARCHAR(20),
    email VARCHAR(100),
    contact_person VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS clients (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(100) NOT NULL,
    prenom VARCHAR(100) NOT NULL,
    adresse TEXT,
    telephone VARCHAR(20),
    email VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS ventes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id INTEGER REFERENCES clients(id) ON DELETE SET NULL ON UPDATE CASCADE,
    utilisateur_id INTEGER NOT NULL REFERENCES utilisateurs(id)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    date_vente TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    montant_total DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    remise DECIMAL(5,2) NOT NULL DEFAULT 0.00,
    mode_paiement VARCHAR(20) NOT NULL DEFAULT 'ESPECES'
        CHECK (mode_paiement IN ('ESPECES', 'MOBILE_MONEY', 'CARTE', 'CREDIT')),
    statut VARCHAR(20) NOT NULL DEFAULT 'VALIDEE'
        CHECK (statut IN ('VALIDEE', 'ANNULEE'))
);

CREATE TABLE IF NOT EXISTS vente_details (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vente_id INTEGER NOT NULL REFERENCES ventes(id) ON DELETE CASCADE ON UPDATE CASCADE,
    medicament_id INTEGER NOT NULL REFERENCES medicaments(id)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    lot_id INTEGER REFERENCES lots_medicaments(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    quantite INTEGER NOT NULL DEFAULT 1 CHECK (quantite > 0),
    prix_unitaire DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    sous_total DECIMAL(10,2) NOT NULL DEFAULT 0.00
);
CREATE INDEX IF NOT EXISTS idx_vente_details_lot ON vente_details (lot_id);

CREATE TABLE IF NOT EXISTS approvisionnements (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fournisseur_id INTEGER NOT NULL REFERENCES fournisseurs(id)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    utilisateur_id INTEGER NOT NULL REFERENCES utilisateurs(id)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    date_appro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    montant_total DECIMAL(10,2) NOT NULL DEFAULT 0.00
);

CREATE TABLE IF NOT EXISTS approvisionnement_details (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    approvisionnement_id INTEGER NOT NULL REFERENCES approvisionnements(id)
        ON DELETE CASCADE ON UPDATE CASCADE,
    medicament_id INTEGER NOT NULL REFERENCES medicaments(id)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    quantite INTEGER NOT NULL DEFAULT 1 CHECK (quantite > 0),
    prix_achat DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    sous_total DECIMAL(10,2) NOT NULL DEFAULT 0.00
);

CREATE TABLE IF NOT EXISTS journal_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id INTEGER REFERENCES utilisateurs(id) ON DELETE SET NULL ON UPDATE CASCADE,
    action VARCHAR(60) NOT NULL,
    entite VARCHAR(60) NOT NULL,
    entite_id INTEGER,
    details TEXT,
    date_action TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_audit_entite ON journal_audit (entite, entite_id);
CREATE INDEX IF NOT EXISTS idx_audit_date ON journal_audit (date_action);

